import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SITE_DIR = path.resolve(__dirname, "..");
const REPO_ROOT = path.resolve(SITE_DIR, "..");

function parseCargoToml(text) {
  const pkgMatch = text.match(/\[package\]([\s\S]*?)(?:\n\[|$)/);
  const pkg = pkgMatch ? pkgMatch[1] : text;
  const pick = (key, fallback = "") => {
    const m = pkg.match(new RegExp(`^${key}\\s*=\\s*"([^"]*)"`, "m"));
    return m ? m[1] : fallback;
  };
  return {
    name: pick("name", "warpd-rs"),
    version: pick("version", "0.2.2"),
    rustVersion: pick("rust-version", "1.88"),
    description: pick("description", "keyboard-driven virtual pointer for Wayland"),
    license: pick("license", "MIT"),
    repository: pick("repository", "https://github.com/jesseconis/warpd-rs"),
  };
}

function parseSimpleToml(text) {
  const out = {};
  const lines = text.split(/\r?\n/);
  let i = 0;
  while (i < lines.length) {
    const line = lines[i].trim();
    i += 1;
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();

    if (val.startsWith("[") && !val.endsWith("]")) {
      while (i < lines.length && !val.includes("]")) {
        val += " " + lines[i].trim();
        i += 1;
      }
    }

    if (val.startsWith("[") && val.endsWith("]")) {
      const inner = val.slice(1, -1);
      const items = [...inner.matchAll(/"([^"]*)"/g)].map((m) => m[1]);
      out[key] = items;
    } else if (val === "true" || val === "false") {
      out[key] = val === "true";
    } else if (/^".*"$/.test(val)) {
      out[key] = val.slice(1, -1);
    } else if (/^-?\d+(\.\d+)?$/.test(val)) {
      out[key] = Number(val);
    } else {
      out[key] = val;
    }
  }
  return out;
}

function parseStatsTxt(text) {
  const frameMatch = text.match(/frame:\s*(\d+x\d+)\s+stride=(\d+)\s+format=(\S+)\s+y_invert=(\S+)/);
  const monMatch = text.match(/monitor:\s*name=(\S+)\s+pos=\(([^)]+)\)\s+size=(\d+x\d+)\s+transform=(\S+)/);
  const pipeMatch = text.match(/pipeline:\s*scale=([\d.]+)\s+kernel=(\S+)/);
  const rectMatch = text.match(
    /rects:\s*total=(\d+)\s+kept_primary=(\d+)\s+kept_size_only=(\d+)\s+kept_final=(\d+)\s+used_fallback=(\S+)/
  );
  return {
    raw: text.trim(),
    frame: frameMatch ? frameMatch[1] : "2560x1080",
    format: frameMatch ? frameMatch[3] : "Argb8888",
    monitor: monMatch ? monMatch[1] : "HDMI-A-2",
    kernel: pipeMatch ? pipeMatch[2] : "4x3",
    totalRects: rectMatch ? Number(rectMatch[1]) : 1754,
    keptPrimary: rectMatch ? Number(rectMatch[2]) : 706,
    keptFinal: rectMatch ? Number(rectMatch[4]) : 706,
  };
}

function discoverExtraDocs(docsDir) {
  if (!fs.existsSync(docsDir)) return [];
  const entries = fs.readdirSync(docsDir, { withFileTypes: true });
  return entries
    .filter((e) => e.isFile() && e.name.toLowerCase().endsWith(".md"))
    .map((e) => {
      const slug = e.name.replace(/\.md$/i, "").toLowerCase().replace(/[^a-z0-9]+/g, "-");
      const content = fs.readFileSync(path.join(docsDir, e.name), "utf8");
      const h1 = content.match(/^#\s+(.+)$/m);
      const title = h1
        ? h1[1].trim()
        : slug
            .split("-")
            .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
            .join(" ");
      return { file: e.name, slug, title, href: `/docs/${slug}/` };
    })
    .sort((a, b) => a.title.localeCompare(b.title));
}

const cargo = parseCargoToml(fs.readFileSync(path.join(REPO_ROOT, "Cargo.toml"), "utf8"));
const configRaw = fs.readFileSync(path.join(REPO_ROOT, "config.example.toml"), "utf8").trim();
const configDefaults = parseSimpleToml(configRaw);
const statsPath = path.join(REPO_ROOT, "docs", "stats.txt");
const detectStats = fs.existsSync(statsPath)
  ? parseStatsTxt(fs.readFileSync(statsPath, "utf8"))
  : parseStatsTxt("");
const extraDocs = discoverExtraDocs(path.join(REPO_ROOT, "docs"));

const generatedDir = path.join(SITE_DIR, "src", "generated");
fs.mkdirSync(generatedDir, { recursive: true });

const output = `// Auto-generated by scripts/sync-content.mjs from Cargo.toml, config.example.toml, and docs/
// Do not edit manually; run \`npm run sync:content\`.

export const REPO_META = ${JSON.stringify(cargo, null, 2)} as const;

export const CONFIG_DEFAULTS = ${JSON.stringify(configDefaults, null, 2)} as const;

export const CONFIG_EXAMPLE_TOML = ${JSON.stringify(configRaw)} as const;

export const DETECT_STATS = ${JSON.stringify(detectStats, null, 2)} as const;

export const EXTRA_DOC_PAGES: ReadonlyArray<{
  file: string;
  slug: string;
  title: string;
  href: string;
}> = ${JSON.stringify(extraDocs, null, 2)};
`;

fs.writeFileSync(path.join(generatedDir, "repoMeta.ts"), output, "utf8");
console.log(
  `[sync-content] synced ${cargo.name} v${cargo.version} (${Object.keys(configDefaults).length} config keys, ${extraDocs.length} extra docs)`
);
